export function validateQuiz(questions) {
  if (!Array.isArray(questions) || questions.length !== 5) throw new Error('실험 퀴즈는 OX 2문제와 5지선다 3문제가 필요합니다.');
  questions.forEach((q, i) => {
    const ids = q.options?.map(([id]) => id) || [];
    if (q.type !== (i < 2 ? 'ox' : 'choice') || ids.length !== (i < 2 ? 2 : 5) || new Set(ids).size !== ids.length || !ids.includes(q.answer) || !q.question?.trim() || !q.explanation?.trim() || q.options.some(([, label]) => !label?.trim()) || (i < 2 && ids.join(',') !== 'O,X')) throw new Error(`퀴즈 ${i + 1}번의 형식이나 정답·해설을 확인하세요.`);
  });
  return questions;
}
